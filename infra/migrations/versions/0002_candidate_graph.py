def _secure_graph_tables() -> None:
    """Row-level security, forced, with the same two policies as every tenant table.

    The tenant policy compares against ``aria_current_tenant()``, which raises when
    the transaction has no scope — so a query that forgets whose data it is about
    fails loudly instead of returning nothing. The maintenance policy exists because
    FORCE applies to the owner too, and aria_migrate has to be able to run a backfill
    (it can drop these tables anyway, so it is not a boundary).
    """
    for table in GRAPH_TABLES:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
        op.execute(
            f"CREATE POLICY tenant_isolation ON {table} FOR ALL TO {APP_ROLE} "
            "USING (tenant_id = aria_current_tenant()) "
            "WITH CHECK (tenant_id = aria_current_tenant())"
        )
        op.execute(
            f"CREATE POLICY maintenance ON {table} FOR ALL TO aria_migrate USING (true) WITH CHECK (true)"
        )
        op.execute(f"GRANT SELECT, INSERT, UPDATE, DELETE ON {table} TO {APP_ROLE}")

    # A fact's text is immutable: an edit appends a revision and moves
    # facts.current_version. Revoking UPDATE makes that a property of the database
    # rather than a convention in the repository (RESUME_ENGINE §1.10).
    op.execute(f"REVOKE UPDATE ON fact_revisions FROM {APP_ROLE}")
    op.execute(
        "COMMENT ON TABLE fact_revisions IS "
        "'Immutable fact text, one row per version. aria_app may insert but not update.'"
    )
    op.execute(
        "COMMENT ON TABLE uploads IS "
        "'Quarantined uploads. original_filename is untrusted and never used as a path.'"
    )


