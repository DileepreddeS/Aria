"""The declarative base and the column helpers every table uses.

Its own module so the platform tables and the candidate graph can share one
``Base`` and one ``MetaData`` without importing each other.
"""

from __future__ import annotations

import datetime as dt
import decimal
import uuid
from typing import Any

from sqlalchemy import Date, DateTime, MetaData, Numeric, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from aria_core.schemas.identity import new_id

__all__ = ["Base", "created_at_column", "month_column", "uuid_primary_key"]

#: Explicit naming so constraints and indexes are stable across autogenerated
#: migrations and can be referenced by name in DDL.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    type_annotation_map = {  # noqa: RUF012  (SQLAlchemy reads this as a plain dict)
        dict[str, Any]: JSONB,
        decimal.Decimal: Numeric(12, 6),
    }


def uuid_primary_key() -> Mapped[uuid.UUID]:
    """Generated in the application, not by the database.

    A row's id is part of the associated data that binds an encrypted S2 value to
    it, so the id has to exist before the value is encrypted (SECURITY.md §10).
    """
    return mapped_column(UUID(as_uuid=True), primary_key=True, default=new_id)


def created_at_column() -> Mapped[dt.datetime]:
    return mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


def month_column(*, nullable: bool = False) -> Mapped[dt.date]:
    """A month, stored as the first day of that month.

    Resumes and job histories are month-precision: "Jun 2024 - Present", never a
    day. Storing a full date invites a false precision that then has to be rendered
    away, and a CHECK constraint in the migration keeps the day at 1 so nothing can
    quietly write one.
    """
    return mapped_column(Date, nullable=nullable)
